#!/usr/bin/env python3
"""make_factory_apps.py — bake the firmware's factory .orbapp containers (D35).

The clock and the HSB editor are ordinary card apps that ship inside the image
instead of on a card (plan §35). This tool is the one author of those two
containers: it lays each one down through the SAME writer the card path uses
(``orbapp.write_container``) and then transcribes the finished bytes into
``main/app/orb_app_factory_blobs.c`` so the installer can read them from flash
as a memory image.

Run it and commit the result whenever a factory container changes:

    python3 tools/make_factory_apps.py

The sentinel lint (tools/host_orbapp_test.py) re-runs this module in --check
mode and byte-compares, the same freshness rule ``bake_clock.py`` serves for
the clock themes, so a hand-edit of the C table is a lint failure and never a
silently-stale factory app.

Deterministic by construction: the two containers carry no art, no code, and no
timestamps beyond ``baked_ms`` — which is pinned to a constant so a rebuild of
an unchanged spec re-emits identical bytes. The header serial is the pair's
version: re-emit with a bumped serial and the boot ladder re-installs (upgrade
in place) on the next flash.
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("orbapp", os.path.join(HERE, "orbapp.py"))
orbapp = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(orbapp)

OUT = os.path.join(HERE, "..", "main", "app", "orb_app_factory_blobs.c")

# Behaviour kind ids must match main/app/orb_app.h's enum (C6 append-only).
KIND_COLOR_PICKER = 1
KIND_CLOCK = 3

# The one owned caps each factory app declares (D19: the declaration is the
# consent). The clock walks the card for theme containers and asks for the D11
# install, so it names sd_read|themes; the picker owns nothing — its three
# settings ride the free config cap, which is not declarable (CAP_FREE).
CLOCK_CAPS = orbapp.cap_bit("sd_read") | orbapp.cap_bit("themes")
PICKER_CAPS = 0

SERIAL = 1          # bump to re-install the pair in place on next boot
BAKED_MS = 0        # pinned constant: the file is content, not a build event

# The picker's three state numbers, declared so they persist inside the row's
# own NVS namespace exactly like any card app's config (C10). The defaults are
# the values color_picker.c's statics carried before D35 — the seed the "mover"
# needs, and the reason there is no migration code.
PICKER_SETTINGS = (
    {"id": "hue", "type": "int", "min": 0, "max": 359, "default": 210},
    {"id": "sat", "type": "int", "min": 0, "max": 100, "default": 80},
    {"id": "bri", "type": "int", "min": 0, "max": 100, "default": 90},
)

APPS = (
    # slug, title, kind, caps, settings
    ("clock",        "Clock", KIND_CLOCK,        CLOCK_CAPS,  ()),
    ("color_picker", "HSB",   KIND_COLOR_PICKER, PICKER_CAPS, PICKER_SETTINGS),
)


def containers():
    """Build each container's bytes with the writer's full ladder of checks.

    write_container derives the filename from the header's slug and insists the
    stem match, so the bytes are authored into a temp dir under the slug's own
    name and read back — the exact card-path artifact, minus the card.
    """
    import tempfile
    out = []
    with tempfile.TemporaryDirectory() as td:
        for slug, title, kind, caps, settings in APPS:
            orbapp.write_container(
                os.path.join(td, slug + ".orbapp"), slug, title, caps=caps,
                settings=settings, behaviour_kind=kind, serial=SERIAL,
                baked_ms=BAKED_MS)
            with open(os.path.join(td, slug + ".orbapp"), "rb") as f:
                blob = f.read()
            out.append((slug, title, kind, caps, blob))
    return out


def emit_c(apps):
    lines = [
        "/* orb_app_factory_blobs.c — GENERATED by tools/make_factory_apps.py. Do not hand-edit.",
        " *",
        " * The firmware's two factory apps as real .orbapp containers, transcribed to",
        " * C arrays so the installer can read them from flash. D35 (plan §35): the",
        " * clock and the HSB editor reach the dial through orb_app_install's ordinary",
        " * doors with these bytes as the read source — same header, same CRC ladder,",
        " * same slot geometry, same keys the /apps page shows.",
        " */",
        "#include <stdint.h>",
        "#include <stddef.h>",
        "",
    ]
    for i, (slug, title, kind, caps, blob) in enumerate(apps):
        lines.append("/* \"%s\" (%s): kind %u, caps 0x%X, %d bytes, header CRC'd, serial %u */"
                     % (title, slug, kind, caps, len(blob), SERIAL))
        lines.append("const uint8_t orb_app_factory_blob_%d[%d] = {" % (i, len(blob)))
        for off in range(0, len(blob), 16):
            chunk = blob[off:off + 16]
            lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",")
        lines.append("};")
        lines.append("")
    lines.append("const uint32_t orb_app_factory_blob_len_%d = %d;" % (0, len(apps[0][4])))
    lines.append("const uint32_t orb_app_factory_blob_len_%d = %d;" % (1, len(apps[1][4])))
    lines.append("")
    return "\n".join(lines) + "\n"


def main():
    apps = containers()
    want = emit_c(apps).encode()
    if "--check" in sys.argv[1:]:
        have = open(OUT, "rb").read() if os.path.exists(OUT) else b""
        if have != want:
            sys.stderr.write("orb_app_factory_blobs.c is stale — run tools/make_factory_apps.py\n")
            return 1
        print("factory blobs fresh (%d containers, %d + %d B)"
              % (len(apps), len(apps[0][4]), len(apps[1][4])))
        return 0
    with open(OUT, "wb") as f:
        f.write(want)
    print("wrote %s: clock %d B, color_picker %d B, serial %u"
          % (os.path.relpath(OUT, os.path.join(HERE, "..")),
             len(apps[0][4]), len(apps[1][4]), SERIAL))
    return 0


if __name__ == "__main__":
    sys.exit(main())
