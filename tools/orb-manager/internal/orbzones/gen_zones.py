#!/usr/bin/env python3
"""Regenerate tools/orb-manager/internal/orbzones/zones.go from the firmware's
own s_tz_tbl (main/net/orb_net.c).

The hub serves this table so the join dialog's zone picker lists exactly the
rows the device accepts, at the moment the device is unreachable. The firmware
is the only source; never hand-edit the generated file — re-run this from the
repo root after touching s_tz_tbl:

    python3 tools/orb-manager/internal/orbzones/gen_zones.py

A companion test (zones_parity_test.go in the hub) fails the check if the
generated rows drift from orb_net.c again.
"""
import os
import re

here = os.path.dirname(os.path.abspath(__file__))
repo = os.path.abspath(os.path.join(here, *[os.pardir] * 4))
src = open(os.path.join(repo, "main", "net", "orb_net.c")).read()
m = re.search(r"static const tz_entry_t s_tz_tbl\[\] = \{(.*?)\n\};", src, re.S)
if not m:
    raise SystemExit("s_tz_tbl not found in main/net/orb_net.c")
rows = re.findall(
    r'\{\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\}', m.group(1))
if len(rows) < 10:
    raise SystemExit("suspiciously few zone rows parsed: %d" % len(rows))

out = []
out.append("// Code generated by gen_zones.py from main/net/orb_net.c. DO NOT EDIT.\n"
           "//\n"
           "// The firmware's s_tz_tbl, row for row. This package exists so the hub can\n"
           "// show the join dialog's zone picker while the orb itself is out of reach\n"
           "// (mid-flash, mid-join, or sitting on its provisioning AP with no route from a\n"
           "// wired hub). zones_parity_test.go re-checks this file against the C table on\n"
           "// every make check, so a firmware edit that skips the generator fails the\n"
           "// build instead of shipping a picker that offers zones the device refuses.\n"
           "\n"
           "package orbzones\n"
           "\n"
           "// Zone is one row of the device's table, in the device's own fields.\n"
           "type Zone struct {\n"
           "\tName  string `json:\"name\"`  // the key NVS stores and the POST sends back\n"
           "\tPOSIX string `json:\"posix\"` // the rule the clock actually runs on\n"
           "\tIANA  string `json:\"iana\"`  // the IANA name, when the key is an alias\n"
           "\tLabel string `json:\"label\"` // the city a person would recognize\n"
           "}\n"
           "\n"
           "var table = []Zone{")
for name, posix, iana, label in rows:
    out.append('\t{Name: %-24s POSIX: %-42s IANA: %-26s Label: %s},' % (
        '"%s",' % name, '"%s",' % posix, '"%s",' % iana, '"%s",' % label))
out.append("}\n"
           "\n"
           "// All returns the table. The order is the firmware's: the first five rows are\n"
           "// the ones a US bench reaches for, and UTC leads so a picker always has a\n"
           "// safe default at the top.\n"
           "func All() []Zone { return table }\n"
           "\n"
           "// Count is the row count, for the parity test's own message.\n"
           "const Count = %d\n" % len(rows))
text = re.sub(r"  +", " ", "\n".join(out))  # collapse the alignment padding
open(os.path.join(here, "zones.go"), "w").write(text + "\n")
print("wrote zones.go with %d rows" % len(rows))
