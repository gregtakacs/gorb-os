// The hub's seed (D36, plan §0.11). The firmware ships no apps and no theme: a
// fresh orb boots to the shell menu and waits. These committed files — the Clock
// and HSB .orbapp containers and the built-in orb-default theme — are what the
// box used to bake into the image, and they reach the dial through the doors
// every app and every theme already use: POST /api/v1/sd/app (the card write,
// named by the container's own header), POST /api/v1/apps/install (the worker's
// card-to-slot ladder), POST /api/v1/apps/enable (the owner's word), and the
// theme pair /api/v1/sd/theme + /api/v1/sd/bundle (upload, store, and the
// reboot the store door promises). One path for the starter pair and for every
// third-party file, which is the whole point of the ruling.
//
// The files are committed artifacts generated by tools/make_factory_apps.py and
// tools/make_seed_theme.py; their freshness is pinned host-side by
// tools/host_orbapp_install_test.py and by TestSeedFilesFresh here, which
// re-runs both generators and byte-compares. The route is idempotent against
// its own half-written runs: every step first asks the device what it already
// has, so a re-press after any failure costs a ledger read, not a second copy.

//go:embed seed
var seedFS embed.FS

// seedApp is one starter container: the slug the ledger will carry and the file
// inside seed/. The order is the shipping order — the dial first, so a seeded
// board lands on a face and not on an editor.
var seedApps = []struct {
	Slug string
	File string
}{
	{"clock", "seed/clock.orbapp"},
	{"color_picker", "seed/color_picker.orbapp"},
}

const seedThemeFile = "seed/orb-default.orbtheme"

// seedMinFW is the first firmware the seed is written for: v1.1.20, the release
// that took the factory tier out of the image. An older board still carries the
// in-image pair and its boot rung; seeding it would fight the firmware, so the
// gate refuses with the flash instruction instead.
const seedMinFW = "v1.1.20"

// The install poll's leash. The door acks the QUEUE, never the landing — the
// worker owns the copy — so the seed watches the ledger the way the /apps page
// does. themeStoreBudget's posture applies: a device still saying busy outruns
// the soft deadline once and dies at the hard stop, not at a timeout that
// would re-issue a job the worker already holds. Vars, so tests run the ladder
// on a clock a copy cannot hide behind.
var (
	seedInstallWait = 45 * time.Second
	seedInstallPoll = 1000 * time.Millisecond
	seedInstallHard = 4 * time.Minute
	seedRebootWait  = 75 * time.Second
)

// seedStep is one streamed line of a seed run, NDJSON the way /api/flash and
// /api/provision stream theirs — a seed crosses WiFi and takes minutes, and a
// silent spinner over that is indistinguishable from a hang.
type seedStep struct {
	Step   string `json:"step"`           // clock | color_picker | theme | seed
	Action string `json:"action"`         // uploaded, installing, installed, enabled, uploaded-theme, storing, stored, rebooting, skipped, done, refused
	Note   string `json:"note,omitempty"` // the device's sentence on a refusal, the hub's on a skip
}

type seedRequest struct {
	IP string `json:"ip"`
}

// handleSeed runs the whole seed for one orb and streams the steps. The gates
// are every device-dialing route's: the address must be one this hub learned
// (checkedTarget), the port claim is held across the run so the liveness sweep
// cannot pulse DTR into a board mid-store (the hold handleThemeInstall holds,
// for its documented reason), and every mutation is the device's own door —
// the hub never re-cuts a rule the dial already enforces.
func (s *Server) handleSeed(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, "POST only", http.StatusMethodNotAllowed)
		return
	}
	var req seedRequest
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		s.jsonErr(w, "bad request: "+err.Error())
		return
	}
	if _, ok := s.checkedTarget(w, req.IP, "", false); !ok {
		return
	}
	release, rerr := s.holdDevicePort(r.Context(), req.IP, deviceTimeout)
	if rerr != nil {
		s.jsonErr(w, rerr.Error())
		return
	}
	defer release()

	flusher, _ := w.(http.Flusher)
	send := func(st seedStep) {
		b, _ := json.Marshal(st)
		w.Write(append(b, "\n"...))
		if flusher != nil {
			flusher.Flush()
		}
	}

	ctx, cancel := context.WithTimeout(r.Context(), 12*time.Minute)
	defer cancel()
	if err := s.seedRun(ctx, req.IP, send); err != nil {
		send(seedStep{Step: "seed", Action: "refused", Note: err.Error()})
		return
	}
	send(seedStep{Step: "seed", Action: "done"})
	log.Printf("orb-manager: seeded the starter apps onto %s", req.IP)
}

// seedRun is the route's body: gate reads, then Clock, then HSB, then the theme
// only if the clock is on the dial — D36's rule that the skeleton theme rides
// with the clock, so a board whose owner keeps only the picker never takes a
// theme nobody asked for.
func (s *Server) seedRun(ctx context.Context, ip string, send func(seedStep)) error {
	st, err := s.device.Status(ip)
	if err != nil {
		return fmt.Errorf("the orb did not answer its status: %w", err)
	}
	if v, ok := firmware.ParseVersion(st.FW); !ok {
		return fmt.Errorf("the dial reports %q, which is not a versioned firmware: flash it to %s first", st.FW, seedMinFW)
	} else if v.Compare(mustVersion(seedMinFW)) < 0 {
		return fmt.Errorf("the dial runs %s and the seed ships for %s and newer: flash it first", st.FW, seedMinFW)
	}
	listing, err := s.device.AppsList(ip)
	if err != nil {
		return fmt.Errorf("the orb did not answer its app ledger: %w", err)
	}
	if !listing.Mounted {
		return fmt.Errorf("no card in the socket — the seed lands files on the card, so insert or mount one first")
	}

	for _, app := range seedApps {
		if err := s.seedOneApp(ctx, ip, app.Slug, app.File, send); err != nil {
			return err
		}
	}
	if s.seedClockLive(ip) {
		if err := s.seedTheme(ctx, ip, send); err != nil {
			return err
		}
	}
	return nil
}

// seedOneApp brings one starter slug onto the dial: on the card, in a slot,
// turned on. Each half asks the device first, so a re-press after any partial
// costs a read, not a second copy, and an owner's hand-installed clock is
// honored untouched — only its enable word may get written, and only off.
func (s *Server) seedOneApp(ctx context.Context, ip, slug, file string, send func(seedStep)) error {
	blob, err := seedFileBytes(file)
	if err != nil {
		return err
	}
	listing, err := s.device.AppsList(ip)
	if err != nil {
		return fmt.Errorf("the orb did not answer its app ledger: %w", err)
	}
	for _, row := range listing.Installed {
		if row.Slug == slug {
			send(seedStep{Step: slug, Action: "skipped", Note: "already on the dial"})
			if !row.Enabled && !row.Failed {
				if _, e := s.device.AppEnable(ip, slug, true); e != nil {
					return fmt.Errorf("enabling %s: %w", slug, deviceSentence(e))
				}
				send(seedStep{Step: slug, Action: "enabled"})
			}
			return nil
		}
	}

	// The card write, unless the file already sits there clean. A row the dial
	// refuses (bad CRC, foreign slug) is the operator's fact to read, not the
	// seed's to overwrite.
	onCard := false
	for _, row := range listing.Apps {
		if row.Stem == slug {
			if !row.OK {
				return fmt.Errorf("%s.orbapp sits on the card but the dial refuses it: %s", slug, row.Why)
			}
			onCard = true
			break
		}
	}
	if !onCard {
		if _, err := s.device.AppUpload(ip, blob, true); err != nil {
			return fmt.Errorf("writing %s to the card: %w", slug, deviceSentence(err))
		}
		send(seedStep{Step: slug, Action: "uploaded"})
	}

	// The install: queue it, then watch the ledger for the row.
	if _, err := s.device.AppInstallCard(ip, slug); err != nil {
		return fmt.Errorf("installing %s: %w", slug, deviceSentence(err))
	}
	send(seedStep{Step: slug, Action: "installing"})
	deadline := time.Now().Add(seedInstallWait)
	hard := time.Now().Add(seedInstallHard)
	for {
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-time.After(seedInstallPoll):
		}
		list, err := s.device.AppsList(ip)
		if err == nil {
			found := false
			for _, row := range list.Installed {
				if row.Slug == slug {
					found = true
					break
				}
			}
			if found {
				send(seedStep{Step: slug, Action: "installed"})
				if _, e := s.device.AppEnable(ip, slug, true); e != nil {
					return fmt.Errorf("enabling %s: %w", slug, deviceSentence(e))
				}
				send(seedStep{Step: slug, Action: "enabled"})
				return nil
			}
			// A row that failed the ladder's own gates shows up refused on the
			// card with a fresh install refusing to appear: name it rather than
			// let the poll run blind.
			for _, row := range list.Apps {
				if row.Stem == slug && !row.OK {
					return fmt.Errorf("the dial refused %s after the install: %s", slug, row.Why)
				}
			}
		}
		if time.Now().After(hard) {
			return fmt.Errorf("%s did not land within %s — the copy may still be running; press seed again to check", slug, seedInstallHard)
		}
		if time.Now().After(deadline) {
			deadline = time.Now().Add(seedInstallWait) // a patient board gets one full extension, then the hard stop
		}
	}
}

// seedClockLive asks the ledger the one question the theme gate needs, at the
// moment it needs it: is a clock row on the dial right now.
func (s *Server) seedClockLive(ip string) bool {
	list, err := s.device.AppsList(ip)
	if err != nil {
		return false
	}
	for _, row := range list.Installed {
		if row.Slug == "clock" && !row.Failed {
			return true
		}
	}
	return false
}

// seedTheme pushes the built-in theme only onto a dial that has no face: an
// owner's themes on the card, or an installed theme in the slot, both stop the
// seed cold — the shelf is the owner's. The store door reboots the board by
// design (the single-slot store IS the theme change), so the run watches the
// landing through waitForStore and then waits for the dial to answer again.
func (s *Server) seedTheme(ctx context.Context, ip string, send func(seedStep)) error {
	tl, err := s.device.ThemeList(ip)
	if err != nil {
		return fmt.Errorf("the orb did not answer its theme list: %w", err)
	}
	if tl.Active != "" || len(tl.Themes) > 0 {
		send(seedStep{Step: "theme", Action: "skipped", Note: "the dial already carries themes"})
		return nil
	}
	blob, err := seedFileBytes(seedThemeFile)
	if err != nil {
		return err
	}
	c, err := orbnet.ContainerName(blob)
	if err != nil {
		return err
	}
	if _, err := s.ota.ThemeUpload(ip, blob, false); err != nil {
		return fmt.Errorf("writing the built-in theme to the card: %w", deviceSentence(err))
	}
	s.dropPreviews(ip)
	send(seedStep{Step: "theme", Action: "uploaded-theme"})
	// The upload door files the bytes and queues the store itself
	// (h_theme_upload’s post_bundle tail) — a second ThemeStore press here
	// would be a second copy for the same promise, so the wait starts at the
	// door’s ack exactly where handleThemeUpload’s does.
	send(seedStep{Step: "theme", Action: "storing"})
	outcome, note := s.waitForStore(ctx, ip, c.ID)
	if outcome != "stored" {
		return fmt.Errorf("the store did not land: %s", note)
	}
	send(seedStep{Step: "theme", Action: "stored"})
	send(seedStep{Step: "theme", Action: "rebooting"})
	if !s.seedWaitBack(ip) {
		return fmt.Errorf("the dial stored the theme but has not answered again within %s", seedRebootWait)
	}
	return nil
}

// seedWaitBack polls the short status client until the orb answers again — the
// store's own reboot, waited out inside the port hold so no sweep races it.
func (s *Server) seedWaitBack(ip string) bool {
	deadline := time.Now().Add(seedRebootWait)
	for time.Now().Before(deadline) {
		select {
		case <-time.After(time.Second):
		}
		if _, err := s.orb.Status(ip); err == nil {
			return true
		}
	}
	return false
}

// seedFileBytes reads one seed file out of the embedded tree, so the hub's
// download build carries the bytes with no disk to look at.
func seedFileBytes(name string) ([]byte, error) {
	b, err := seedFS.ReadFile(name)
	if err != nil {
		return nil, fmt.Errorf("the hub's built-in seed is missing %s: %w", name, err)
	}
	return b, nil
}

// seedHashes names the sha256 of every embedded seed file — the freshness
// witness the test reads, and one honest line in the startup log.
func seedHashes() (map[string]string, error) {
	out := map[string]string{}
	for _, app := range seedApps {
		b, err := seedFS.ReadFile(app.File)
		if err != nil {
			return nil, err
		}
		sum := sha256.Sum256(b)
		out[app.File] = hex.EncodeToString(sum[:])
	}
	b, err := seedFS.ReadFile(seedThemeFile)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(b)
	out[seedThemeFile] = hex.EncodeToString(sum[:])
	return out, nil
}

// mustVersion parses seedMinFW, which is a constant written in the scheme;
// a failure is a source bug and must crash at startup, not negotiate at runtime.
func mustVersion(raw string) firmware.Version {
	v, ok := firmware.ParseVersion(raw)
	if !ok {
		panic("seed.go: seedMinFW is not a versioned stamp: " + raw)
	}
	return v
}

// deviceSentence unwraps an orbnet.DeviceError to the firmware's own words, so
// a refusal streamed here is the sentence the door gave and not Go's.
func deviceSentence(err error) error {
	if de, ok := err.(*orbnet.DeviceError); ok {
		var env struct {
			Error  string `json:"error"`
			Detail string `json:"detail"`
		}
		if json.Unmarshal(de.Body, &env) == nil && env.Error != "" {
			msg := env.Error
			if env.Detail != "" {
				msg += ": " + env.Detail
			}
			return fmt.Errorf("%s", msg)
		}
	}
	return err
}

func init() {
	// A hub whose built-in seed cannot be read refuses to start, the way a hub
	// with no readable firmware bundle does: a button that cannot work is a
	// startup failure, not a runtime surprise.
	if _, err := seedHashes(); err != nil {
		log.Fatalf("orb-manager: built-in seed unreadable: %v", err)
	}
}
