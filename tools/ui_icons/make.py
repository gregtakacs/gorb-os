#!/usr/bin/env python3
"""Regenerate the drawn cards (app-platform-plan §61).

    python3 tools/ui_icons/make.py

Draws the three cards (draw.py) and writes:
  main/assets/orb_ui_icons.c   Settings at 466 px and Back at 300 px, each an RGB565 disc
                               (theme_schema.disc_pack) deflated, for orb_inflate
  apps/color_picker/icon.png   HSB's icon at 232 px, which orbsdk compiles into its module

--check compares instead of writing, for make check-host."""
import os
import subprocess
import sys
import tempfile
import zlib

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import theme_schema  # noqa: E402

C_OUT = os.path.join(ROOT, "main", "assets", "orb_ui_icons.c")
ICON_OUT = os.path.join(ROOT, "apps", "color_picker", "icon.png")
CARDS = (("settings", 466), ("back", 300))


def rgb565_disc(im, side):
    im = im.convert("RGB").resize((side, side), Image.BOX)
    px = im.tobytes()
    sq = bytearray(side * side * 2)
    for i in range(side * side):
        r, g, b = px[3 * i], px[3 * i + 1], px[3 * i + 2]
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        sq[2 * i] = v & 0xFF
        sq[2 * i + 1] = v >> 8
    return theme_schema.disc_pack(bytes(sq), side=side)


def c_array(name, data):
    rows = [", ".join("0x%02x" % b for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return ("const uint8_t %s[%d] __attribute__((aligned(4))) = {\n    %s\n};\n"
            % (name, len(data), ",\n    ".join(rows)))


def main():
    check = "--check" in sys.argv
    with tempfile.TemporaryDirectory() as td:
        subprocess.run([sys.executable, os.path.join(HERE, "draw.py"), td], check=True,
                       stdout=subprocess.DEVNULL)
        parts = ["/* GENERATED by tools/ui_icons/make.py from tools/ui_icons/draw.py: do not edit.\n"
                 " * The drawn cards the firmware carries (app-platform-plan §61): RGB565 discs\n"
                 " * (orb_disc.h), deflated with a zlib wrapper for orb_inflate. */\n"
                 "#include \"orb_ui_icons.h\"\n\n"]
        for name, side in CARDS:
            z = zlib.compress(rgb565_disc(Image.open(os.path.join(td, name + ".png")), side), 9)
            parts.append(c_array("orb_ui_icon_%s_z" % name, z))
            parts.append("const uint32_t orb_ui_icon_%s_n = %d;\nconst uint16_t orb_ui_icon_%s_side = %d;\n\n"
                         % (name, len(z), name, side))
        c_text = "".join(parts)
        icon = Image.open(os.path.join(td, "hsb.png")).convert("RGB").resize((232, 232), Image.BOX)
        icon_path = os.path.join(td, "icon.png")
        icon.save(icon_path, optimize=False)
        icon_bytes = open(icon_path, "rb").read()
    if check:
        bad = []
        if not os.path.exists(C_OUT) or open(C_OUT).read() != c_text:
            bad.append(C_OUT)
        if not os.path.exists(ICON_OUT) or open(ICON_OUT, "rb").read() != icon_bytes:
            bad.append(ICON_OUT)
        if bad:
            sys.exit("drawn cards out of date (run tools/ui_icons/make.py): " + ", ".join(bad))
        print("drawn cards current")
        return
    with open(C_OUT, "w") as f:
        f.write(c_text)
    with open(ICON_OUT, "wb") as f:
        f.write(icon_bytes)
    print("wrote", os.path.relpath(C_OUT, ROOT), "and", os.path.relpath(ICON_OUT, ROOT))


if __name__ == "__main__":
    main()
